# apps/documents/services/google_oauth.py
"""
Google Drive OAuth 2.0 Central Archive Service.

Mendukung upload ke Google Drive dengan SATU akun pusat INTERMILAN.
HANYA admin/superuser boleh authorize. Operator cukup upload.

ROOT FOLDER STRATEGY:
1. Jika GOOGLE_DRIVE_ROOT_FOLDER_ID diset → gunakan langsung
2. Jika kosong → app buat folder otomatis via Drive API
3. Folder ID disimpan di media/drive_tokens/archive_folder_id.json
4. Folder creation idempotent (cari dulu, baru buat jika tidak ada)

CREDENTIAL SECURITY:
- OAuth client_id/client_secret: dari environment variable
- Central token: disimpan di media/drive_tokens/archive_oauth.json (gitignored)
- Folder ID: disimpan di media/drive_tokens/archive_folder_id.json (gitignored)
- Tidak ada credential di source code atau log

CARA PERGANTIAN AKUN:
1. Hapus file token: media/drive_tokens/archive_oauth.json
2. Hapus folder ID: media/drive_tokens/archive_folder_id.json
3. Admin authorize ulang dengan akun baru
4. Folder root akan dibuat ulang secara otomatis
"""

import os
import json
from pathlib import Path
from typing import Optional

from django.conf import settings


# OAuth 2.0 Scopes - least privilege
SCOPES = [
    "https://www.googleapis.com/auth/drive.file",
]


class GoogleOAuthError(Exception):
    """Base exception for Google OAuth errors."""
    pass


class OAuthCredentialsNotConfigured(GoogleOAuthError):
    """OAuth credentials not configured in environment."""
    pass


class OAuthTokenNotFound(GoogleOAuthError):
    """Central OAuth token not found."""
    pass


class OAuthRefreshFailed(GoogleOAuthError):
    """Failed to refresh OAuth token."""
    pass


# =============================================================================
# CONFIGURATION
# =============================================================================

def get_oauth_config() -> dict:
    """
    Ambil konfigurasi OAuth dari environment variables.

    Environment variables yang diperlukan:
    - GOOGLE_DRIVE_OAUTH_CLIENT_ID: OAuth 2.0 Client ID dari Google Cloud Console
    - GOOGLE_DRIVE_OAUTH_CLIENT_SECRET: OAuth 2.0 Client Secret
    - GOOGLE_DRIVE_OAUTH_REDIRECT_URI: Redirect URI

    Returns:
        dict dengan client_id, client_secret, redirect_uri

    Raises:
        OAuthCredentialsNotConfigured: Jika credential tidak ditemukan
    """
    client_id = os.environ.get("GOOGLE_DRIVE_OAUTH_CLIENT_ID", "").strip()
    client_secret = os.environ.get("GOOGLE_DRIVE_OAUTH_CLIENT_SECRET", "").strip()
    redirect_uri = os.environ.get("GOOGLE_DRIVE_OAUTH_REDIRECT_URI", "").strip()

    if not client_id or not client_secret:
        raise OAuthCredentialsNotConfigured(
            "OAuth credentials not configured. "
            "Set GOOGLE_DRIVE_OAUTH_CLIENT_ID and GOOGLE_DRIVE_OAUTH_CLIENT_SECRET."
        )

    return {
        "client_id": client_id,
        "client_secret": client_secret,
        "redirect_uri": redirect_uri or "http://localhost:8000/documents/drive/oauth/callback/",
    }


def get_central_token_path() -> Path:
    """
    Path penyimpanan token OAuth central aplikasi.

    Returns:
        Path ke file token (media/drive_tokens/archive_oauth.json)
    """
    token_dir = Path(settings.MEDIA_ROOT) / "drive_tokens"
    token_dir.mkdir(parents=True, exist_ok=True)
    return token_dir / "archive_oauth.json"


def get_root_folder_id_path() -> Path:
    """
    Path penyimpanan folder ID central aplikasi.

    Returns:
        Path ke file folder ID (media/drive_tokens/archive_folder_id.json)
    """
    token_dir = Path(settings.MEDIA_ROOT) / "drive_tokens"
    token_dir.mkdir(parents=True, exist_ok=True)
    return token_dir / "archive_folder_id.json"


def get_root_folder_name() -> str:
    """
    Nama folder root untuk archive.

    Can be overridden via environment variable GOOGLE_DRIVE_ROOT_FOLDER_NAME.

    Returns:
        Nama folder root
    """
    return os.environ.get(
        "GOOGLE_DRIVE_ROOT_FOLDER_NAME",
        "INTERMILAN - TEST ARSIP"  # Default for testing
    ).strip()


